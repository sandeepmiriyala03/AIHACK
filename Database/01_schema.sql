-- ─────────────────────────────────────────────────────────────────────────────
-- Staff directory — Neon PostgreSQL schema (yuktai v5.1 agentic grid)
-- Run once in the Neon SQL Editor. Safe to re-run: every statement is
-- idempotent and works whether or not an "employees" table already exists.
-- ─────────────────────────────────────────────────────────────────────────────

-- Fast "contains" search on names (ILIKE '%ravi%') for 1M rows
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- ── Departments ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS departments (
  id   integer PRIMARY KEY,
  name text    NOT NULL UNIQUE
);

-- ── Employees ───────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS employees (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text          NOT NULL,
  salary       numeric(10,2) NOT NULL DEFAULT 0,
  age          integer,
  departmentid integer,
  joined_on    date
);

-- Older tables (from "data insert.sql") may lack the newer column
ALTER TABLE employees ADD COLUMN IF NOT EXISTS joined_on date;

-- Sensible limits (added only if missing)
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'employees_salary_check') THEN
    ALTER TABLE employees ADD CONSTRAINT employees_salary_check CHECK (salary >= 0) NOT VALID;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'employees_age_check') THEN
    ALTER TABLE employees ADD CONSTRAINT employees_age_check CHECK (age IS NULL OR age BETWEEN 14 AND 100) NOT VALID;
  END IF;
END $$;

-- ── Indexes: every filter and sort the grid agent can send ─────────────────
CREATE INDEX IF NOT EXISTS employees_salary_idx     ON employees (salary);
CREATE INDEX IF NOT EXISTS employees_age_idx        ON employees (age);
CREATE INDEX IF NOT EXISTS employees_department_idx ON employees (departmentid);
CREATE INDEX IF NOT EXISTS employees_joined_on_idx  ON employees (joined_on);
CREATE INDEX IF NOT EXISTS employees_name_lower_idx ON employees (lower(name) text_pattern_ops);  -- equals / starts with
CREATE INDEX IF NOT EXISTS employees_name_trgm_idx  ON employees USING gin (name gin_trgm_ops);   -- contains

-- ── View the API reads from: department name instead of id ─────────────────
CREATE OR REPLACE VIEW staff_directory AS
SELECT
  e.id,
  e.name,
  e.salary,
  e.age,
  e.departmentid,
  COALESCE(d.name, 'Unassigned') AS department,
  e.joined_on
FROM employees e
LEFT JOIN departments d ON d.id = e.departmentid;
